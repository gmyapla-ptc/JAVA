public class Lesson3_Arithmetic {
    public static void main(String[] args) {
     int minerals = 10;
     int ships = 3;
     System.out.println(minerals + ships);
     System.out.println(minerals - ships);
     System.out.println(minerals * ships);
     System.out.println(minerals / ships);
     System.out.println(minerals % ships);


     // + ADDITION
     // - SUBTRACTION
    // * MULTIPLICATION
    // / DIVISION
     // % MODULUS
    }
}