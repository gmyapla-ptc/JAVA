public class Lesson5_Comparison_Operators {
    public static void main (String[]args) {
        
        /* 
        COMPARISON OPERATORS
        >   // greater than
        <   // less than
        ==  // equal to
        !=  // not equal to
        >=  // greater than OR equal to
        <=  // less than OR equal to
        */
        
        System.out.println(10 > 5);
        System.out.println(10 < 5);
        System.out.println(10 == 5);
        System.out.println(10 != 5);
        
        int imperials = 100;
        int heretics = 150;
        
        System.out.println();
        System.out.println("EXAMPLE");
        System.out.println("IMPERIALS EST NUM IS 100");
        System.out.println("HERETICS EST NUM IS 150");
        System.out.println();
        
        System.out.println("Is Imperials greater than Heretics?");
        System.out.println(imperials > heretics);
        System.out.println("Is Imperials less than Heretics?");
        System.out.println(imperials < heretics);
        System.out.println("Are they equal?");
        System.out.println(imperials == heretics);
        System.out.println("Are they not equal?");
        System.out.println(imperials != heretics);
        System.out.println("Is IMPERIALS less than or equal to 100?");
        System.out.println(imperials <= 100);
        
        
        
        
        
    }
    
}
